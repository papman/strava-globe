// ─── Polyline encoder ─────────────────────────────────────────────────────────
// Encodes an array of [lat, lng] pairs into a Google-encoded polyline string

function encode(coords) {
  let out = "", prevLat = 0, prevLng = 0;
  for (const [lat, lng] of coords) {
    const rLat = Math.round(lat * 1e5);
    const rLng = Math.round(lng * 1e5);
    for (let val of [rLat - prevLat, rLng - prevLng]) {
      val = val < 0 ? ~(val << 1) : val << 1;
      while (val >= 0x20) {
        out += String.fromCharCode((0x20 | (val & 0x1f)) + 63);
        val >>= 5;
      }
      out += String.fromCharCode(val + 63);
    }
    prevLat = rLat;
    prevLng = rLng;
  }
  return out;
}

